/** 시트가 필요로 하는 것 전부 — 목록(이름·날짜)과 내용을 합친 모양 */
export type Til = { id: string; title: string; date: string } & TilContent;

/**
 * 내용이 있는 기록만 시트가 된다.
 *
 * 목록에는 있는데 아직 안 쓴 날이 있을 수 있다 — 그런 노드는 그래프에 서 있되
 * 열리지 않는다. 내용 없는 이론 노드와 같은 규칙이다.
 */
export const tils: Til[] = tilEntries.flatMap((entry) => {
  const content = contents.find((candidate) => candidate.id === entry.id);
  return content ? [{ ...entry, ...content }] : [];
});

export function getTil(id: string): Til | undefined {
  return tils.find((til) => til.id === id);
}
